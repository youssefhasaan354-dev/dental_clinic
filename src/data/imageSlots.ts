export function getSlotById(id: string): ImageSlot | undefined {
  return ALL_IMAGE_SLOTS.find((s) => s.id === id);
}

export const getImageSlotById = getSlotById;

export function resolveSlotMedia(
  slot: ImageSlot,
  override?: Partial<ImageSlot> & { url?: string; alt?: { ar?: string; en?: string } }
) {
  const isVideoAllowed = slot.allowVideo !== false;
  const rawMediaType = override?.mediaType || slot.mediaType || 'image';
  const mediaType = isVideoAllowed ? rawMediaType : 'image';

  return {
    url: override?.url || override?.currentUrl || slot.currentUrl || slot.defaultUrl,
    posterUrl: override?.posterUrl || slot.posterUrl,
    mediaType,
    altText: {
      ar: override?.alt?.ar || override?.altText?.ar || slot.altText?.ar || '',
      en: override?.alt?.en || override?.altText?.en || slot.altText?.en || '',
    },
    aspectRatio: override?.aspectRatio || slot.aspectRatio,
    edgeFade: override?.edgeFade !== undefined ? override.edgeFade : (slot.edgeFade ?? (slot.id === 'slot-hero')),
  };
}
